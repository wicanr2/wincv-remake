//! IBM 代碼頁 437 與 Unicode 的對照。原版的 .FON 字模依 CP437 排列,
//! 半形字要先換回位元組才能取字模。

/// CP437 的 256 個字元。0x20–0x7E 是 ASCII 本身。
pub const CP437: [char; 256] = build();

const fn build() -> [char; 256] {
    let mut t = ['\0'; 256];
    let hi: [char; 32] = [
        '\0', '☺', '☻', '♥', '♦', '♣', '♠', '•', '◘', '○', '◙', '♂', '♀', '♪', '♫', '☼',
        '►', '◄', '↕', '‼', '¶', '§', '▬', '↨', '↑', '↓', '→', '←', '∟', '↔', '▲', '▼',
    ];
    let up: [char; 128] = [
        'Ç', 'ü', 'é', 'â', 'ä', 'à', 'å', 'ç', 'ê', 'ë', 'è', 'ï', 'î', 'ì', 'Ä', 'Å',
        'É', 'æ', 'Æ', 'ô', 'ö', 'ò', 'û', 'ù', 'ÿ', 'Ö', 'Ü', '¢', '£', '¥', '₧', 'ƒ',
        'á', 'í', 'ó', 'ú', 'ñ', 'Ñ', 'ª', 'º', '¿', '⌐', '¬', '½', '¼', '¡', '«', '»',
        '░', '▒', '▓', '│', '┤', '╡', '╢', '╖', '╕', '╣', '║', '╗', '╝', '╜', '╛', '┐',
        '└', '┴', '┬', '├', '─', '┼', '╞', '╟', '╚', '╔', '╩', '╦', '╠', '═', '╬', '╧',
        '╨', '╤', '╥', '╙', '╘', '╒', '╓', '╫', '╪', '┘', '┌', '█', '▄', '▌', '▐', '▀',
        'α', 'ß', 'Γ', 'π', 'Σ', 'σ', 'µ', 'τ', 'Φ', 'Θ', 'Ω', 'δ', '∞', 'φ', 'ε', '∩',
        '≡', '±', '≥', '≤', '⌠', '⌡', '÷', '≈', '°', '∙', '·', '√', 'ⁿ', '²', '■', '\u{00A0}',
    ];
    let mut i = 0;
    while i < 32 {
        t[i] = hi[i];
        i += 1;
    }
    let mut b = 0x20;
    while b <= 0x7E {
        t[b] = b as u8 as char;
        b += 1;
    }
    let mut j = 0;
    while j < 128 {
        t[0x80 + j] = up[j];
        j += 1;
    }
    t
}

/// 把字元換回 CP437 位元組。表裡沒有重複的字元,所以反查只有一個答案;
/// 0x00 與 0x7F 沒有字元,不參與反查(與 Go 版相同)。
pub fn from_cp437(r: char) -> Option<u8> {
    let c = r as u32;
    if (0x20..=0x7E).contains(&c) {
        return Some(c as u8);
    }
    if r == '\0' {
        return None;
    }
    CP437.iter().position(|&v| v == r).map(|i| i as u8)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn round_trip_all_defined() {
        for b in 1..=255u8 {
            let r = CP437[b as usize];
            if r == '\0' {
                continue; // 0x7F
            }
            assert_eq!(from_cp437(r), Some(b), "0x{b:02X} {r:?}");
        }
        assert_eq!(from_cp437('中'), None);
    }
}
